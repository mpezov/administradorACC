BEGIN;

CREATE TABLE IF NOT EXISTS public.bim_local_cache_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_version_id bigint NOT NULL
        REFERENCES public.bim_local_versions(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    cache_key varchar(64) NOT NULL,
    remote_path text NOT NULL,
    range_header text,
    local_relpath text NOT NULL,
    status_code integer NOT NULL DEFAULT 200,
    content_type text,
    content_encoding text,
    content_range text,
    accept_ranges text,
    etag text,
    last_modified text,
    size_bytes bigint NOT NULL DEFAULT 0,
    cached_at timestamptz NOT NULL DEFAULT now(),
    last_accessed_at timestamptz NOT NULL DEFAULT now(),
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE(local_version_id, cache_key)
);

CREATE INDEX IF NOT EXISTS idx_bim_local_cache_files_version
    ON public.bim_local_cache_files(local_version_id);

CREATE INDEX IF NOT EXISTS idx_bim_local_cache_files_access
    ON public.bim_local_cache_files(local_version_id, last_accessed_at DESC);

COMMIT;
