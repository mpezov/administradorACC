BEGIN;

CREATE TABLE IF NOT EXISTS public.bim_project_types (
    type_code text PRIMARY KEY,
    display_name text NOT NULL,
    description text,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.bim_layer_profiles (
    profile_code text PRIMARY KEY,
    project_type text REFERENCES public.bim_project_types(type_code)
        ON UPDATE CASCADE ON DELETE SET NULL,
    display_name text NOT NULL,
    description text,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.bim_layer_profile_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_code text NOT NULL REFERENCES public.bim_layer_profiles(profile_code)
        ON UPDATE CASCADE ON DELETE CASCADE,
    layer_code text NOT NULL,
    display_name text NOT NULL,
    selector jsonb NOT NULL DEFAULT '{"status":"PENDING_CONFIGURATION"}'::jsonb,
    default_visible boolean NOT NULL DEFAULT true,
    required boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL DEFAULT 100,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(profile_code, layer_code)
);

CREATE TABLE IF NOT EXISTS public.bim_projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code text NOT NULL UNIQUE,
    cui varchar(10),
    wvs varchar(20),
    acc_project_guid text UNIQUE REFERENCES public.acc_projects(id_guid)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    project_type text REFERENCES public.bim_project_types(type_code)
        ON UPDATE CASCADE ON DELETE SET NULL,
    viewer_enabled boolean NOT NULL DEFAULT true,
    managerial_profile text REFERENCES public.bim_layer_profiles(profile_code)
        ON UPDATE CASCADE ON DELETE SET NULL,
    local_project_key text NOT NULL UNIQUE,
    srid integer,
    notes text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_bim_projects_cui
    ON public.bim_projects(cui);
CREATE INDEX IF NOT EXISTS idx_bim_projects_wvs
    ON public.bim_projects(wvs);
CREATE INDEX IF NOT EXISTS idx_bim_projects_acc_guid
    ON public.bim_projects(acc_project_guid);

CREATE TABLE IF NOT EXISTS public.bim_project_models (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES public.bim_projects(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    model_code text NOT NULL,
    model_role text NOT NULL DEFAULT 'MANAGERIAL',
    acc_item_id text REFERENCES public.acc_items(item_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    source_filename_cache text,
    acc_folder_id_cache text,
    acc_folder_path_cache text,
    format text,
    is_default boolean NOT NULL DEFAULT false,
    enabled boolean NOT NULL DEFAULT true,
    download_policy text NOT NULL DEFAULT 'AUTO',
    notes text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(project_id, model_code),
    CHECK(download_policy IN ('AUTO','ON_DEMAND','MANUAL'))
);

CREATE INDEX IF NOT EXISTS idx_bim_project_models_project
    ON public.bim_project_models(project_id);
CREATE INDEX IF NOT EXISTS idx_bim_project_models_acc_item
    ON public.bim_project_models(acc_item_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_bim_project_default_model
    ON public.bim_project_models(project_id)
    WHERE is_default = true AND enabled = true;

CREATE TABLE IF NOT EXISTS public.bim_local_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id bigint NOT NULL REFERENCES public.bim_project_models(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    acc_version_id text NOT NULL,
    version_urn text,
    version_number integer,
    viewable_guid text,
    derivative_format text DEFAULT 'SVF',
    local_root text NOT NULL,
    local_entry text,
    manifest_path text,
    layers_cache_path text,
    status text NOT NULL DEFAULT 'PENDING',
    is_active boolean NOT NULL DEFAULT false,
    source_last_modified timestamptz,
    download_started_at timestamptz,
    downloaded_at timestamptz,
    verified_at timestamptz,
    size_bytes bigint,
    file_count integer,
    checksum text,
    last_error text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(model_id, acc_version_id),
    CHECK(status IN ('PENDING','DOWNLOADING','READY','FAILED','ACTIVE','RETIRED'))
);

CREATE INDEX IF NOT EXISTS idx_bim_local_versions_model
    ON public.bim_local_versions(model_id);
CREATE INDEX IF NOT EXISTS idx_bim_local_versions_acc_version
    ON public.bim_local_versions(acc_version_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_bim_local_active_version
    ON public.bim_local_versions(model_id)
    WHERE is_active = true;

CREATE TABLE IF NOT EXISTS public.bim_project_layer_overrides (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES public.bim_projects(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    layer_code text NOT NULL,
    display_name_override text,
    selector_override jsonb,
    visible_override boolean,
    enabled boolean NOT NULL DEFAULT true,
    sort_order_override integer,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(project_id, layer_code)
);

CREATE TABLE IF NOT EXISTS public.bim_extension_catalog (
    extension_code text PRIMARY KEY,
    display_name text NOT NULL,
    description text,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.bim_project_extensions (
    project_id bigint NOT NULL REFERENCES public.bim_projects(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    extension_code text NOT NULL REFERENCES public.bim_extension_catalog(extension_code)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    enabled boolean NOT NULL DEFAULT true,
    config jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(project_id, extension_code)
);

CREATE TABLE IF NOT EXISTS public.project_kpi_catalog (
    kpi_code text PRIMARY KEY,
    display_name text NOT NULL,
    unit text,
    value_type text NOT NULL DEFAULT 'NUMERIC',
    source_default text,
    sort_order integer NOT NULL DEFAULT 100,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK(value_type IN ('NUMERIC','TEXT','BOOLEAN'))
);

CREATE TABLE IF NOT EXISTS public.project_kpi_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES public.bim_projects(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    kpi_code text NOT NULL REFERENCES public.project_kpi_catalog(kpi_code)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    report_date date NOT NULL,
    period_label text,
    value_numeric numeric,
    value_text text,
    value_boolean boolean,
    source text NOT NULL,
    source_ref text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    loaded_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(project_id, kpi_code, report_date, source),
    CHECK (
        (value_numeric IS NOT NULL)::int +
        (value_text IS NOT NULL)::int +
        (value_boolean IS NOT NULL)::int <= 1
    )
);

CREATE INDEX IF NOT EXISTS idx_project_kpi_snapshots_project_date
    ON public.project_kpi_snapshots(project_id, report_date DESC);

-- Trigger genérico de updated_at, aislado bajo nombre bim_*.
CREATE OR REPLACE FUNCTION public.bim_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END
$$;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'bim_project_types',
        'bim_layer_profiles',
        'bim_layer_profile_items',
        'bim_projects',
        'bim_project_models',
        'bim_local_versions',
        'bim_project_layer_overrides',
        'bim_extension_catalog',
        'bim_project_extensions',
        'project_kpi_catalog'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_touch ON public.%I', t, t);
        EXECUTE format(
            'CREATE TRIGGER trg_%I_touch BEFORE UPDATE ON public.%I
             FOR EACH ROW EXECUTE FUNCTION public.bim_touch_updated_at()',
            t, t
        );
    END LOOP;
END $$;

COMMENT ON TABLE public.bim_projects IS
'Catálogo maestro de proyectos habilitados para el Visor BIM Universal. No sustituye proyectos_avance ni acc_projects.';
COMMENT ON TABLE public.bim_project_models IS
'Configura qué item ACC representa cada modelo del visor. La identidad técnica es acc_item_id, no el nombre del archivo.';
COMMENT ON TABLE public.bim_local_versions IS
'Histórico local versionado de bubbles SVF/PF. Nunca mezclar archivos de versiones distintas.';
COMMENT ON COLUMN public.bim_layer_profile_items.selector IS
'Regla estable para resolver una capa por propiedades/archivo/categoría. No almacenar dbIds permanentes aquí.';

COMMIT;
