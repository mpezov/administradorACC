BEGIN;

CREATE TABLE IF NOT EXISTS public.bim_remote_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id bigint NOT NULL REFERENCES public.bim_project_models(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    acc_version_id text NOT NULL,
    derivative_urn text,
    manifest_url text,
    derivative_format text,
    default_viewable_guid text,
    status text NOT NULL DEFAULT 'UNKNOWN',
    source_last_modified timestamptz,
    checked_at timestamptz NOT NULL DEFAULT now(),
    last_error text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(model_id, acc_version_id),
    CHECK(status IN ('UNKNOWN','READY','PROCESSING','MISSING','ERROR'))
);

CREATE INDEX IF NOT EXISTS idx_bim_remote_versions_model
    ON public.bim_remote_versions(model_id);

CREATE INDEX IF NOT EXISTS idx_bim_remote_versions_version
    ON public.bim_remote_versions(acc_version_id);

DROP TRIGGER IF EXISTS trg_bim_remote_versions_touch ON public.bim_remote_versions;
CREATE TRIGGER trg_bim_remote_versions_touch
BEFORE UPDATE ON public.bim_remote_versions
FOR EACH ROW EXECUTE FUNCTION public.bim_touch_updated_at();

CREATE OR REPLACE VIEW public.v_bim_viewer_state AS
SELECT
    bp.id AS project_id,
    bp.project_code,
    bp.acc_project_guid,
    m.id AS model_id,
    m.model_code,
    m.model_role,
    m.acc_item_id,
    m.is_default,
    m.enabled,
    i.item_name,
    i.ext,
    i.folder_path_cached,
    i.latest_version_id AS acc_latest_version_id,
    i.last_modified AS acc_last_modified,
    i.is_active AS acc_item_active,
    rv.id AS remote_version_id,
    rv.derivative_urn,
    rv.derivative_format,
    rv.default_viewable_guid,
    rv.status AS remote_status,
    rv.checked_at AS remote_checked_at,
    rv.last_error AS remote_error,
    lv.id AS local_version_id,
    lv.acc_version_id AS local_acc_version_id,
    lv.derivative_format AS local_derivative_format,
    lv.local_root,
    lv.local_entry,
    lv.status AS local_status,
    lv.is_active AS local_is_active,
    CASE
        WHEN COALESCE(i.is_active,false)=false THEN 'ACC_ITEM_INACTIVE'
        WHEN lv.id IS NOT NULL
             AND lv.acc_version_id=i.latest_version_id
             AND lv.is_active=true
             AND lv.status IN ('READY','ACTIVE') THEN 'LOCAL_READY'
        WHEN rv.id IS NOT NULL
             AND rv.acc_version_id=i.latest_version_id
             AND rv.status='READY' THEN 'REMOTE_READY'
        WHEN rv.id IS NOT NULL
             AND rv.acc_version_id=i.latest_version_id
             AND rv.status='PROCESSING' THEN 'PROCESSING'
        WHEN rv.id IS NOT NULL
             AND rv.acc_version_id=i.latest_version_id
             AND rv.status='MISSING' THEN 'SOURCE_ONLY'
        WHEN rv.id IS NOT NULL
             AND rv.acc_version_id=i.latest_version_id
             AND rv.status='ERROR' THEN 'ERROR'
        WHEN lv.id IS NOT NULL
             AND lv.acc_version_id IS DISTINCT FROM i.latest_version_id THEN 'UPDATE_AVAILABLE'
        ELSE 'NEED_CHECK'
    END AS viewer_status
FROM public.bim_projects bp
JOIN public.bim_project_models m
  ON m.project_id=bp.id
 AND m.model_role='MANAGERIAL'
 AND m.is_default=true
 AND m.enabled=true
LEFT JOIN public.acc_items i ON i.item_id=m.acc_item_id
LEFT JOIN public.bim_remote_versions rv
  ON rv.model_id=m.id
 AND rv.acc_version_id=i.latest_version_id
LEFT JOIN LATERAL (
    SELECT x.*
    FROM public.bim_local_versions x
    WHERE x.model_id=m.id
    ORDER BY
      (x.acc_version_id=i.latest_version_id) DESC,
      x.is_active DESC,
      x.downloaded_at DESC NULLS LAST,
      x.id DESC
    LIMIT 1
) lv ON true;

COMMIT;
